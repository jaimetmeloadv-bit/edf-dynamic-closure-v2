def main() -> None:
    config = Config()
    output_dir = Path(config.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    dimensions = algebra_dimension_table(config)
    dimensions.to_csv(
        output_dir / "generator_algebra_dimensions.csv",
        index=False,
    )

    fourier = pd.DataFrame(
        [
            verify_fourier_duality(k)
            for k in range(config.k_min, config.k_max + 1)
        ]
    )
    fourier.to_csv(
        output_dir / "fourier_duality_diagnostics.csv",
        index=False,
    )

    gauge = gauge_diagnostics_table(config)
    gauge.to_csv(
        output_dir / "gauge_equivalence_trials.csv",
        index=False,
    )

    gauge_summary = (
        gauge.groupby("k", as_index=False)
        .agg(
            max_cycle_closure_error=("cycle_closure_error", "max"),
            max_gauge_to_shift_error=("gauge_to_shift_error", "max"),
            max_gauge_phase_commutator_error=(
                "gauge_phase_commutator_error",
                "max",
            ),
            max_dressed_weyl_relation_error=(
                "dressed_weyl_relation_error",
                "max",
            ),
        )
    )
    gauge_summary.to_csv(
        output_dir / "gauge_equivalence_summary.csv",
        index=False,
    )

    phase_dynamics = phase_dynamics_table(config)
    phase_dynamics.to_csv(
        output_dir / "phase_only_dynamics_diagnostics.csv",
        index=False,
    )

    plot_algebra_dimensions(dimensions, output_dir)
    plot_dimension_ratio(dimensions, output_dir)
    plot_gauge_errors(gauge_summary, output_dir)
    plot_phase_occupation_invariance(phase_dynamics, output_dir)

    phase_only_verified = bool(
        np.all(
            dimensions["phase_only_dimension"]
            == dimensions["expected_single_generator_dimension"]
        )
    )

    shift_only_verified = bool(
        np.all(
            dimensions["shift_only_dimension"]
            == dimensions["expected_single_generator_dimension"]
        )
    )

    pair_verified = bool(
        np.all(
            dimensions["phase_shift_dimension"]
            == dimensions["expected_pair_dimension"]
        )
    )

    print()
    print("Dynamic Closure Notebook — Entry 06")
    print("Why a Cyclic Dynamic Closure Requires Phase and Shift")
    print("-" * 64)
    print()
    print(
        "Phase-only algebra dimension equals k for all tested k: "
        f"{phase_only_verified}"
    )
    print(
        "Shift-only algebra dimension equals k for all tested k: "
        f"{shift_only_verified}"
    )
    print(
        "Phase + shift algebra dimension equals k^2 for all tested k: "
        f"{pair_verified}"
    )
    print()
    print(
        "Maximum Fourier duality error F^dagger Z F = X: "
        f"{fourier['Fdag_Z_F_minus_X_error'].max():.6e}"
    )
    print(
        "Maximum Fourier duality error F^dagger X F = Z^(-1): "
        f"{fourier['Fdag_X_F_minus_Zinv_error'].max():.6e}"
    )
    print()
    print(
        "Maximum closed-traversal gauge-to-shift error across all trials: "
        f"{gauge['gauge_to_shift_error'].max():.6e}"
    )
    print(
        "Maximum dressed Weyl-relation error across all trials: "
        f"{gauge['dressed_weyl_relation_error'].max():.6e}"
    )
    print()
    print(
        "Maximum occupation change under phase-only action: "
        f"{phase_dynamics['phase_only_occupation_change_L1'].max():.6e}"
    )
    print()
    print("Structural conclusion:")
    print(
        "    Phase distinguishability supplies Z; actual cyclic traversal "
        "supplies X up to gauge."
    )
    print(
        "    Either generator alone spans only a k-dimensional commutative "
        "algebra; together they span M_k(C), dimension k^2."
    )
    print()
